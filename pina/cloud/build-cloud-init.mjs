#!/usr/bin/env node
// Builds pina/cloud/cloud-init.yaml from the package files, so there is one source of truth.
// Usage: node pina/cloud/build-cloud-init.mjs [--check]
// --check exits 1 when the committed cloud-init.yaml is out of date.
import fs from "node:fs";
import path from "node:path";
import zlib from "node:zlib";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const pkg = path.resolve(here, "..");
const out = path.join(here, "cloud-init.yaml");

// [source path inside pina/, destination on the server]
const files = [
  ["cloud/setup.sh", "/opt/pina/setup.sh", "0755"],
  ["cloud/docker-compose.yml", "/opt/pina/docker-compose.yml", "0644"],
  ["cloud/Dockerfile", "/opt/pina/Dockerfile", "0644"],
  ["config/openclaw.json5", "/opt/pina/template/openclaw.json5", "0644"],
];
// Every workspace file except the CLAUDE.md symlink (a repo convention, not part of the agent's home).
function walk(dir, rel = "") {
  for (const entry of fs.readdirSync(path.join(dir, rel), { withFileTypes: true })) {
    const r = path.join(rel, entry.name);
    if (entry.isDirectory()) walk(dir, r);
    else if (entry.isFile() && entry.name !== "CLAUDE.md") {
      files.push([path.join("workspace", r), path.posix.join("/opt/pina/template/workspace", r.split(path.sep).join("/")), "0644"]);
    }
  }
}
walk(path.join(pkg, "workspace"));
files.sort((a, b) => a[1].localeCompare(b[1]));

const envBlock = `      # 1. Your Anthropic API key (console.anthropic.com > API Keys). Starts with sk-ant-
      ANTHROPIC_API_KEY=CHANGE_ME
      # 2. Your Telegram bot token from @BotFather. Looks like 123456789:AAE...
      TELEGRAM_BOT_TOKEN=CHANGE_ME
      # 3. Your own Telegram user id: the number @userinfobot replies with.
      OWNER_TELEGRAM_ID=CHANGE_ME
      # 4. Optional: a free Gemini key from aistudio.google.com turns on web search.
      GEMINI_API_KEY=
      # Your time zone for reminders and the morning briefing.
      OPENCLAW_TZ=Europe/Prague
`;

const lines = [
  "#cloud-config",
  "# Piña: your assistant's own computer. Paste this whole file into the \"User data\" /",
  "# \"Cloud config\" box when you create an Ubuntu 24.04 server.",
  "# Before pasting, replace the three CHANGE_ME values just below. Leave everything else as it is.",
  "# Setup takes about 5-10 minutes. Piña sends you a Telegram message when it is ready.",
  "# Generated by pina/cloud/build-cloud-init.mjs. Edit the source files, not this file.",
  "write_files:",
  "  - path: /opt/pina/.env",
  '    permissions: "0600"',
  "    content: |",
  envBlock.replace(/\n$/, ""),
];
for (const [src, dest, mode] of files) {
  const body = fs.readFileSync(path.join(pkg, src));
  const b64 = zlib.gzipSync(body, { level: 9, mtime: 0 }).toString("base64");
  lines.push(`  - path: ${dest}`, `    permissions: "${mode}"`, "    encoding: gz+b64", `    content: ${b64}`);
}
lines.push("runcmd:", "  - [bash, /opt/pina/setup.sh]", "");
const yaml = lines.join("\n");

if (process.argv.includes("--check")) {
  const current = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
  if (current !== yaml) { console.error("cloud-init.yaml is out of date. Run: node pina/cloud/build-cloud-init.mjs"); process.exit(1); }
  console.log("cloud-init.yaml is up to date."); process.exit(0);
}
fs.writeFileSync(out, yaml);
console.log(`Wrote ${path.relative(process.cwd(), out)} (${Buffer.byteLength(yaml)} bytes, ${files.length + 1} files)`);
