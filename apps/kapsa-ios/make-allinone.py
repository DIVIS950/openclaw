#!/usr/bin/env python3
"""Join the Kapsa iOS sources into one file you can paste into Xcode or Swift Playgrounds.

Usage: python3 apps/kapsa-ios/make-allinone.py
Writes apps/kapsa-ios/Kapsa-AllInOne.swift (imports deduplicated at the top).
"""

from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCES = HERE / "Kapsa"
OUT = HERE / "Kapsa-AllInOne.swift"

# App entry first, then data, services and screens.
ORDER = [
    "KapsaApp.swift",
    "Strings.swift",
    "Models.swift",
    "Brands.swift",
    "Look.swift",
    "Barcode.swift",
    "Store.swift",
    "Demo.swift",
    "Notifier.swift",
    "Location.swift",
    "Logos.swift",
    "Scanner.swift",
    "Components.swift",
    "WalletView.swift",
    "CardDetailView.swift",
    "Sheets.swift",
    "CardForm.swift",
    "CouponsView.swift",
    "StatsView.swift",
    "SettingsView.swift",
]


def main() -> None:
    names = ORDER + sorted(p.name for p in SOURCES.glob("*.swift") if p.name not in ORDER)
    imports: set[str] = set()
    bodies: list[str] = []
    for name in names:
        lines = (SOURCES / name).read_text(encoding="utf-8").splitlines()
        kept = []
        for line in lines:
            if line.startswith("import "):
                imports.add(line.strip())
            else:
                kept.append(line)
        body = "\n".join(kept).strip("\n")
        bodies.append(f"// MARK: - {name}\n\n{body}\n")
    header = (
        "// Kapsa for iPhone: loyalty cards, gift cards and coupons that pop up by themselves\n"
        "// when you walk into the shop. One file: paste it into a new Xcode iOS App project\n"
        "// (or a Swift Playgrounds app) in place of the files the template made.\n"
        "// Steps: apps/kapsa-ios/README.md. Generated by make-allinone.py; edit Kapsa/*.swift.\n\n"
    )
    text = header + "\n".join(sorted(imports)) + "\n\n" + "\n".join(bodies)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(HERE.parent.parent)} ({len(text.splitlines())} lines)")


if __name__ == "__main__":
    main()
